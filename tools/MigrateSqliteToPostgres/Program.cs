using Microsoft.Data.Sqlite;
using Npgsql;
using NpgsqlTypes;

var sourcePath = args.Length > 0
    ? Path.GetFullPath(args[0])
    : Path.GetFullPath(Path.Combine(Directory.GetCurrentDirectory(), "App_Data", "easybusiness.sqlite3"));
var targetConnectionString = args.Length > 1
    ? args[1]
    : Environment.GetEnvironmentVariable("ConnectionStrings__EasyBusiness");

if (!File.Exists(sourcePath))
    throw new FileNotFoundException("The SQLite database was not found. Stop the old app first and provide its path.", sourcePath);
if (string.IsNullOrWhiteSpace(targetConnectionString))
    throw new InvalidOperationException("Provide the PostgreSQL connection string as the second argument or ConnectionStrings__EasyBusiness.");

Console.WriteLine($"Source: {sourcePath}");
Console.WriteLine("The SQLite source is read-only. PostgreSQL will receive the migrated data.");

await using var sqlite = new SqliteConnection(new SqliteConnectionStringBuilder
{
    DataSource = sourcePath,
    Mode = SqliteOpenMode.ReadOnly,
    Cache = SqliteCacheMode.Private
}.ToString());
await sqlite.OpenAsync();

await using var postgres = new NpgsqlConnection(targetConnectionString);
await postgres.OpenAsync();
await EnsureSchemaAsync(postgres);
await using var transaction = await postgres.BeginTransactionAsync();

await CopyUsersAsync(sqlite, postgres, transaction);
await CopySessionsAsync(sqlite, postgres, transaction);
await CopyPasswordResetTokensAsync(sqlite, postgres, transaction);
await CopyUserModuleAccessAsync(sqlite, postgres, transaction);
await CopyBusinessRecordsAsync(sqlite, postgres, transaction);
await CopyAuditEventsAsync(sqlite, postgres, transaction);
await CopyFiscalSubmissionsAsync(sqlite, postgres, transaction);
await CopyPosSaleItemsAsync(sqlite, postgres, transaction);
await transaction.CommitAsync();

await ResetSequencesAsync(postgres);
await ValidateCountsAsync(sqlite, postgres);
Console.WriteLine("Migration completed successfully.");

static async Task EnsureSchemaAsync(NpgsqlConnection connection)
{
    await using var command = connection.CreateCommand();
    command.CommandText = """
        CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            display_name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
            password_salt BYTEA NOT NULL, password_hash BYTEA NOT NULL,
            role TEXT NOT NULL CHECK(role IN ('Administrator', 'User')),
            company_role TEXT NOT NULL DEFAULT 'Staff', created_at TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS sessions (
            token_hash TEXT PRIMARY KEY, csrf_token TEXT NOT NULL,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            expires_at TEXT NOT NULL, created_at TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS password_reset_tokens (
            user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
            token_hash TEXT NOT NULL UNIQUE, expires_at TEXT NOT NULL, created_at TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS user_module_access (
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            module TEXT NOT NULL, PRIMARY KEY(user_id, module)
        );
        CREATE TABLE IF NOT EXISTS business_records (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            module TEXT NOT NULL, name TEXT NOT NULL, payload_json JSONB NOT NULL,
            created_at TEXT NOT NULL, updated_at TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS audit_events (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT REFERENCES users(id), action TEXT NOT NULL,
            module TEXT NOT NULL, record_id BIGINT, created_at TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS fiscal_submissions (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            local_record_id BIGINT NOT NULL, status TEXT NOT NULL,
            response_summary TEXT, created_at TEXT NOT NULL
        );
        CREATE TABLE IF NOT EXISTS pos_sale_items (
            sale_record_id BIGINT NOT NULL REFERENCES business_records(id) ON DELETE CASCADE,
            product_id BIGINT NOT NULL, product_name TEXT NOT NULL, sku TEXT NOT NULL,
            quantity INTEGER NOT NULL CHECK(quantity > 0), unit_price NUMERIC NOT NULL CHECK(unit_price >= 0),
            returned_quantity INTEGER NOT NULL DEFAULT 0 CHECK(returned_quantity >= 0 AND returned_quantity <= quantity),
            PRIMARY KEY(sale_record_id, product_id)
        );
        CREATE INDEX IF NOT EXISTS ix_password_reset_tokens_expiry ON password_reset_tokens(expires_at);
        CREATE INDEX IF NOT EXISTS ix_sessions_expiry ON sessions(expires_at);
        CREATE INDEX IF NOT EXISTS ix_records_owner_module ON business_records(owner_id, module, created_at DESC);
        CREATE INDEX IF NOT EXISTS ix_pos_sale_items_product ON pos_sale_items(product_id);
        """;
    await command.ExecuteNonQueryAsync();
}

static async Task CopyUsersAsync(SqliteConnection source, NpgsqlConnection target, NpgsqlTransaction tx)
{
    await CopyAsync(source, target, tx, "SELECT id, display_name, email, password_salt, password_hash, role, company_role, created_at FROM users",
        "INSERT INTO users(id, display_name, email, password_salt, password_hash, role, company_role, created_at) VALUES(@id,@name,@email,@salt,@hash,@role,@company,@created) ON CONFLICT DO NOTHING",
        (reader, command) => { Add(command, "id", reader.GetInt64(0)); Add(command, "name", reader.GetString(1)); Add(command, "email", reader.GetString(2)); AddBytes(command, "salt", (byte[])reader[3]); AddBytes(command, "hash", (byte[])reader[4]); Add(command, "role", reader.GetString(5)); Add(command, "company", reader.GetString(6)); Add(command, "created", reader.GetString(7)); });
}

static async Task CopySessionsAsync(SqliteConnection source, NpgsqlConnection target, NpgsqlTransaction tx) =>
    await CopyAsync(source, target, tx, "SELECT token_hash, csrf_token, user_id, expires_at, created_at FROM sessions", "INSERT INTO sessions(token_hash,csrf_token,user_id,expires_at,created_at) VALUES(@hash,@csrf,@user,@expires,@created) ON CONFLICT DO NOTHING", (r,c) => { Add(c,"hash",r.GetString(0)); Add(c,"csrf",r.GetString(1)); Add(c,"user",r.GetInt64(2)); Add(c,"expires",r.GetString(3)); Add(c,"created",r.GetString(4)); });

static async Task CopyPasswordResetTokensAsync(SqliteConnection source, NpgsqlConnection target, NpgsqlTransaction tx) =>
    await CopyAsync(source, target, tx, "SELECT user_id, token_hash, expires_at, created_at FROM password_reset_tokens", "INSERT INTO password_reset_tokens(user_id,token_hash,expires_at,created_at) VALUES(@user,@hash,@expires,@created) ON CONFLICT DO NOTHING", (r,c) => { Add(c,"user",r.GetInt64(0)); Add(c,"hash",r.GetString(1)); Add(c,"expires",r.GetString(2)); Add(c,"created",r.GetString(3)); });

static async Task CopyUserModuleAccessAsync(SqliteConnection source, NpgsqlConnection target, NpgsqlTransaction tx) =>
    await CopyAsync(source, target, tx, "SELECT user_id, module FROM user_module_access", "INSERT INTO user_module_access(user_id,module) VALUES(@user,@module) ON CONFLICT DO NOTHING", (r,c) => { Add(c,"user",r.GetInt64(0)); Add(c,"module",r.GetString(1)); });

static async Task CopyBusinessRecordsAsync(SqliteConnection source, NpgsqlConnection target, NpgsqlTransaction tx) =>
    await CopyAsync(source, target, tx, "SELECT id, owner_id, module, name, payload_json, created_at, updated_at FROM business_records", "INSERT INTO business_records(id,owner_id,module,name,payload_json,created_at,updated_at) VALUES(@id,@owner,@module,@name,@payload,@created,@updated) ON CONFLICT DO NOTHING", (r,c) => { Add(c,"id",r.GetInt64(0)); Add(c,"owner",r.GetInt64(1)); Add(c,"module",r.GetString(2)); Add(c,"name",r.GetString(3)); AddJson(c,"payload",r.GetString(4)); Add(c,"created",r.GetString(5)); Add(c,"updated",r.GetString(6)); });

static async Task CopyAuditEventsAsync(SqliteConnection source, NpgsqlConnection target, NpgsqlTransaction tx) =>
    await CopyAsync(source, target, tx, "SELECT id, user_id, action, module, record_id, created_at FROM audit_events", "INSERT INTO audit_events(id,user_id,action,module,record_id,created_at) VALUES(@id,@user,@action,@module,@record,@created) ON CONFLICT DO NOTHING", (r,c) => { Add(c,"id",r.GetInt64(0)); AddNullable(c,"user",r.IsDBNull(1)?null:r.GetInt64(1)); Add(c,"action",r.GetString(2)); Add(c,"module",r.GetString(3)); AddNullable(c,"record",r.IsDBNull(4)?null:r.GetInt64(4)); Add(c,"created",r.GetString(5)); });

static async Task CopyFiscalSubmissionsAsync(SqliteConnection source, NpgsqlConnection target, NpgsqlTransaction tx) =>
    await CopyAsync(source, target, tx, "SELECT id, owner_id, local_record_id, status, response_summary, created_at FROM fiscal_submissions", "INSERT INTO fiscal_submissions(id,owner_id,local_record_id,status,response_summary,created_at) VALUES(@id,@owner,@record,@status,@summary,@created) ON CONFLICT DO NOTHING", (r,c) => { Add(c,"id",r.GetInt64(0)); Add(c,"owner",r.GetInt64(1)); Add(c,"record",r.GetInt64(2)); Add(c,"status",r.GetString(3)); AddNullable(c,"summary",r.IsDBNull(4)?null:r.GetString(4)); Add(c,"created",r.GetString(5)); });

static async Task CopyPosSaleItemsAsync(SqliteConnection source, NpgsqlConnection target, NpgsqlTransaction tx) =>
    await CopyAsync(source, target, tx, "SELECT sale_record_id, product_id, product_name, sku, quantity, unit_price, returned_quantity FROM pos_sale_items", "INSERT INTO pos_sale_items(sale_record_id,product_id,product_name,sku,quantity,unit_price,returned_quantity) VALUES(@sale,@product,@name,@sku,@quantity,@price,@returned) ON CONFLICT DO NOTHING", (r,c) => { Add(c,"sale",r.GetInt64(0)); Add(c,"product",r.GetInt64(1)); Add(c,"name",r.GetString(2)); Add(c,"sku",r.GetString(3)); Add(c,"quantity",r.GetInt32(4)); Add(c,"price",Convert.ToDecimal(r[5], System.Globalization.CultureInfo.InvariantCulture)); Add(c,"returned",r.GetInt32(6)); });

static async Task CopyAsync(SqliteConnection source, NpgsqlConnection target, NpgsqlTransaction tx, string selectSql, string insertSql, Action<SqliteDataReader, NpgsqlCommand> map)
{
    await using var select = source.CreateCommand();
    select.CommandText = selectSql;
    await using var reader = await select.ExecuteReaderAsync();
    while (await reader.ReadAsync())
    {
        await using var insert = target.CreateCommand();
        insert.Transaction = tx;
        insert.CommandText = insertSql;
        map(reader, insert);
        await insert.ExecuteNonQueryAsync();
    }
}

static async Task ResetSequencesAsync(NpgsqlConnection connection)
{
    await using var command = connection.CreateCommand();
    command.CommandText = """
        SELECT setval(pg_get_serial_sequence('users','id'), COALESCE((SELECT MAX(id) FROM users), 1), EXISTS(SELECT 1 FROM users));
        SELECT setval(pg_get_serial_sequence('business_records','id'), COALESCE((SELECT MAX(id) FROM business_records), 1), EXISTS(SELECT 1 FROM business_records));
        SELECT setval(pg_get_serial_sequence('audit_events','id'), COALESCE((SELECT MAX(id) FROM audit_events), 1), EXISTS(SELECT 1 FROM audit_events));
        SELECT setval(pg_get_serial_sequence('fiscal_submissions','id'), COALESCE((SELECT MAX(id) FROM fiscal_submissions), 1), EXISTS(SELECT 1 FROM fiscal_submissions));
        """;
    await command.ExecuteNonQueryAsync();
}

static async Task ValidateCountsAsync(SqliteConnection source, NpgsqlConnection target)
{
    foreach (var table in new[] { "users", "sessions", "password_reset_tokens", "user_module_access", "business_records", "audit_events", "fiscal_submissions", "pos_sale_items" })
    {
        await using var sourceCommand = source.CreateCommand();
        sourceCommand.CommandText = $"SELECT COUNT(*) FROM {table}";
        var expected = Convert.ToInt64(await sourceCommand.ExecuteScalarAsync());
        await using var targetCommand = target.CreateCommand();
        targetCommand.CommandText = $"SELECT COUNT(*) FROM {table}";
        var actual = Convert.ToInt64(await targetCommand.ExecuteScalarAsync());
        if (expected != actual)
            throw new InvalidOperationException($"Row count mismatch for {table}: SQLite={expected}, PostgreSQL={actual}.");
        Console.WriteLine($"{table}: {actual} rows");
    }
}

static void Add(NpgsqlCommand command, string name, object value) => command.Parameters.AddWithValue(name, value);
static void AddNullable(NpgsqlCommand command, string name, object? value) => command.Parameters.AddWithValue(name, value ?? DBNull.Value);
static void AddBytes(NpgsqlCommand command, string name, byte[] value) => command.Parameters.Add(name, NpgsqlDbType.Bytea).Value = value;
static void AddJson(NpgsqlCommand command, string name, string value) => command.Parameters.Add(name, NpgsqlDbType.Jsonb).Value = value;
